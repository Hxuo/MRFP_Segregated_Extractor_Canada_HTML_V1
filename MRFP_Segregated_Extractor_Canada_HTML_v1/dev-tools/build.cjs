'use strict';
const fs=require('fs'),path=require('path'),root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'dev-tools/fmc-manifest.json'),'utf8'));
if(!Array.isArray(manifest)||!manifest.length)throw Error('FMC manifest empty');
const keys=new Set();
for(const a of manifest){
 if(!/^[a-z][a-z0-9_]*$/.test(a.key)||!/^js\/fmc\/[a-z][a-z0-9_]*\.js$/.test(a.file)||a.file!=='js/fmc/'+a.key+'.js')throw Error('Invalid FMC entry '+JSON.stringify(a));
 if(keys.has(a.key))throw Error('Duplicate FMC '+a.key);keys.add(a.key);
 if(!fs.existsSync(path.join(root,a.file)))throw Error('Missing '+a.file);
}
const core=['shared-utils','document-indexer','fund-segmenter','fmc-registry','evidence-engine','extraction-engine'];
const src=[...core.map(x=>'js/core/'+x+'.js'),...manifest.map(x=>x.file)].map(f=>'\n/* '+f+' */\n'+fs.readFileSync(path.join(root,f),'utf8')).join('');
const bundled='/* Generated by dev-tools/build.cjs; edit source files, never this bundle. */\n(function(root){"use strict";\n'+src+'\nroot.SEGREGATED_ENGINE={extract:extractSegregated,indexDocument,segmentFunds,registry:REGISTRY,sourceEvidence};\n})(globalThis);\n';
fs.writeFileSync(path.join(root,'js/engine.js'),bundled);
fs.writeFileSync(path.join(root,'js/evidence-locator.js'),fs.readFileSync(path.join(root,'js/core/locator-compat.js'),'utf8'));
console.log('Built',manifest.map(x=>x.key).join(','),'engine and evidence locator');
